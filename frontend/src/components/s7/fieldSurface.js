/* frontend/src/components/s7/fieldSurface.js
   Общая проверка для полей формы поиска: было ли нажатие по «фону» плашки.

   ЗАЧЕМ. Три поля — аэропорт, дата, пассажиры — раскрывают своё выпадающее
   окно при нажатии в любое место плашки, а не только по иконке в углу.
   Обработчик висит на корневом элементе .form-group и ловит нажатия по всему,
   включая потомков: сам input, кнопку иконки, кнопки внутри уже раскрытого
   окна. Для них поведение своё, и общий обработчик должен их пропускать.

   ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. Правило одно на три компонента. Скопированное
   трижды, оно разъедется при первой же правке — например, когда в плашку
   добавят ещё одну кнопку и забудут про два других файла.

   ЧТО СЧИТАЕТСЯ «ФОНОМ»: подпись поля, внутренние отступы, сама плашка.
   Всё остальное — интерактивные элементы и содержимое выпадающих окон.
*/

/** Элементы, у которых есть собственная реакция на нажатие. */
const INTERACTIVE = "input, button, a, select, textarea, [role='option'], [contenteditable]";

/** Корни выпадающих окон: внутри них нажатия к плашке отношения не имеют. */
const POPOVERS = ".airport-suggestions, .passenger-dropdown, .calendar-popup";

/**
 * @param {EventTarget} target цель события (обычно event.target)
 * @returns {boolean} true — нажатие пришлось на «фон» плашки
 */
export function isFieldSurface(target) {
    // Событие может прийти из текстового узла или из документа: closest есть
    // только у Element.
    if (!(target instanceof Element)) return false;
    return !target.closest(`${INTERACTIVE}, ${POPOVERS}`);
}
